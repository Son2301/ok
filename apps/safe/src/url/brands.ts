/**
 * Curated list of brands Vietnamese scammers impersonate most, with their official domains.
 *
 * Only domains we are confident belong to the brand are listed: marking a lookalike as
 * "official" would be far worse than missing a real one (a missing official domain only causes a
 * cautious false alarm). Admins can extend/disable entries at runtime via the `brand_overrides`
 * table (PUT /admin/brands/:id). Review this list periodically.
 *
 * Keyword modes:
 *   fuzzy     – substring match + typo/lookalike matching (distinctive, long names)
 *   substring – appears anywhere in the domain label
 *   prefix    – a label token starts with it ("evn" → evn-thanhtoan, evnhcm-cskh)
 *   token     – exact token only (short/ambiguous names: "vcb", "acb", "mb")
 */

export type BrandCategory =
  | 'bank'
  | 'ewallet'
  | 'government'
  | 'ecommerce'
  | 'logistics'
  | 'telco'
  | 'social'
  | 'tech'
  | 'crypto'
  | 'payment'
  | 'insurance'
  | 'media';

export interface BrandKeyword {
  k: string;
  mode: 'fuzzy' | 'substring' | 'prefix' | 'token';
}

export interface Brand {
  id: string;
  name: string;
  category: BrandCategory;
  /** Official registrable domains (or hosts). Subdomains of these are official too. */
  domains: string[];
  keywords: BrandKeyword[];
  /** Folded (no diacritics, lowercase) phrases used to spot the brand in page titles / messages. */
  mentions: string[];
  /** The platform hosts user-generated pages: the domain is real but page content is not vouched for. */
  userContent?: boolean;
}

const f = (k: string): BrandKeyword => ({ k, mode: 'fuzzy' });
const s = (k: string): BrandKeyword => ({ k, mode: 'substring' });
const p = (k: string): BrandKeyword => ({ k, mode: 'prefix' });
const t = (k: string): BrandKeyword => ({ k, mode: 'token' });

