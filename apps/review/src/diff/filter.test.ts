import { describe, expect, it } from 'vitest';
import { classifyFile, DEFAULT_FILTER_OPTIONS, filterFiles } from './filter';
import { matchGlob } from './glob';
import { assessRisk, fileKind, prioritize } from './prioritize';
import type { DiffFile } from './types';

function fakeFile(path: string, opts: Partial<DiffFile> & { added?: string[] } = {}): DiffFile {
  const added = opts.added ?? ['const x = 1;'];
  return {
    oldPath: path,
    newPath: path,
    path,
    status: 'modified',
    binary: false,
    similarity: null,
    oldMode: null,
    newMode: null,
    hunks: [
      {
        oldStart: 1,
        oldLines: 0,
        newStart: 1,
        newLines: added.length,
        section: '',
        lines: added.map((content, i) => ({ type: 'add' as const, content, oldLine: null, newLine: i + 1 })),
      },
    ],
    additions: added.length,
    deletions: 0,
    ...opts,
  };
}

describe('glob', () => {
  it.each([
    ['src/a.ts', '*.ts', true],
    ['src/deep/a.ts', 'src/**/*.ts', true],
    ['src/a.ts', 'src/**/*.ts', true],
    ['lib/a.ts', 'src/**', false],
    ['src/a/b/c.js', 'src/', true],
    ['a.min.js', '*.{js,css}', true],
    ['x/a.lock', '/a.lock', false],
    ['a.lock', '/a.lock', true],
    ['src/a1.ts', 'src/a?.ts', true],
    ['src/ab.ts', 'src/a[0-9].ts', false],
    ['docs/x.md', '**/*.md', true],
    ['generated/x.ts', 'generated/**', true],
  ])('%s vs %s → %s', (path, pattern, expected) => {
    expect(matchGlob(path, pattern)).toBe(expected);
  });
});

describe('classifyFile', () => {
  it.each([
    ['pnpm-lock.yaml', 'lockfile'],
    ['apps/x/package-lock.json', 'lockfile'],
    ['go.sum', 'lockfile'],
    ['vendor/github.com/x/y.go', 'vendored'],
    ['node_modules/x/index.js', 'vendored'],
    ['src/__snapshots__/a.test.ts.snap', 'snapshot'],
    ['public/app.min.js', 'minified'],
    ['dist/index.js', 'generated'],
    ['api/service.pb.go', 'generated'],
    ['assets/logo.png', 'binary'],
    ['src/index.ts', null],
  ])('%s → %s', (path, reason) => {
    expect(classifyFile(fakeFile(path))).toBe(reason);
  });

  it('detects generated banners, minified content, large files, deletions and rename-only files', () => {
    expect(
      classifyFile(fakeFile('src/api.ts', { added: ['// Code generated by protoc. DO NOT EDIT.', 'x'] })),
    ).toBe('generated');
    expect(classifyFile(fakeFile('src/bundle.js', { added: ['x'.repeat(5000)] }))).toBe('minified');
    expect(classifyFile(fakeFile('src/big.ts', { additions: 2000 }))).toBe('large');
    expect(classifyFile(fakeFile('src/gone.ts', { status: 'deleted', newPath: null }))).toBe('deleted');
    expect(classifyFile(fakeFile('src/moved.ts', { status: 'renamed', hunks: [] }))).toBe('no-changes');
    expect(classifyFile(fakeFile('src/x.bin', { binary: true }))).toBe('binary');
  });

  it('applies .okreview.yml include/exclude/force overrides', () => {
    const opts = {
      ...DEFAULT_FILTER_OPTIONS,
      include: ['src/**'],
      exclude: ['src/legacy/**'],
      force: ['src/generated/**'],
    };
    expect(classifyFile(fakeFile('src/a.ts'), opts)).toBeNull();
    expect(classifyFile(fakeFile('lib/a.ts'), opts)).toBe('not-included');
    expect(classifyFile(fakeFile('src/legacy/a.ts'), opts)).toBe('excluded');
    expect(classifyFile(fakeFile('src/generated/client.ts'), opts)).toBeNull();
    expect(classifyFile(fakeFile('src/other/generated/client.ts'), opts)).toBe('generated');
    // force never resurrects binaries/deletions
    expect(classifyFile(fakeFile('src/generated/logo.png'), opts)).toBe('binary');
  });

  it('splits kept and skipped files', () => {
    const { kept, skipped } = filterFiles([fakeFile('src/a.ts'), fakeFile('yarn.lock')]);
    expect(kept.map((f) => f.path)).toEqual(['src/a.ts']);
    expect(skipped).toEqual([{ path: 'yarn.lock', reason: 'lockfile' }]);
  });
});

describe('prioritization', () => {
  it('classifies file kinds', () => {
    expect(fileKind('src/auth.test.ts')).toBe('test');
    expect(fileKind('pkg/handler_test.go')).toBe('test');
    expect(fileKind('README.md')).toBe('docs');
    expect(fileKind('.github/workflows/ci.yml')).toBe('infra');
    expect(fileKind('config/app.yaml')).toBe('config');
    expect(fileKind('src/server.ts')).toBe('source');
  });

  it('orders security source > big source > small source > tests > docs', () => {
    const lines = (n: number) => Array.from({ length: n }, (_, i) => `x${i}`);
    const auth = fakeFile('src/auth/session.ts', { added: lines(3) });
    const migration = fakeFile('db/migrations/0003_users.sql', { added: lines(2) });
    const big = fakeFile('src/report.ts', { added: lines(400) });
    const small = fakeFile('src/format.ts', { added: lines(2) });
    const test = fakeFile('src/auth/session.test.ts', { added: lines(500) });
    const docs = fakeFile('docs/guide.md', { added: lines(900) });
    const order = [docs, test, small, big, migration, auth]
      .map((f) => ({ path: f.path, score: assessRisk(f).score }))
      .sort((a, b) => b.score - a.score)
      .map((x) => x.path);
    expect(order.slice(0, 2).sort()).toEqual(['db/migrations/0003_users.sql', 'src/auth/session.ts']);
    expect(order.slice(2)).toEqual([
      'src/report.ts',
      'src/format.ts',
      'src/auth/session.test.ts',
      'docs/guide.md',
    ]);
  });

  it('selects the riskiest files within the file and line budget', () => {
    const lines = (n: number) => Array.from({ length: n }, (_, i) => `x${i}`);
    const files = [
      fakeFile('src/a.test.ts', { added: lines(10) }),
      fakeFile('src/payments/charge.ts', { added: lines(50) }),
      fakeFile('src/huge.ts', { added: lines(500) }),
      fakeFile('src/util.ts', { added: lines(20) }),
    ];
    const { selected, deferred } = prioritize(files, { maxFiles: 3, maxChangedLines: 100 });
    expect(selected.map((s) => s.file.path)).toEqual([
      'src/payments/charge.ts',
      'src/util.ts',
      'src/a.test.ts',
    ]);
    expect(deferred.map((s) => s.file.path)).toEqual(['src/huge.ts']);
  });

  it('always selects the top file even if it alone exceeds the line budget', () => {
    const { selected } = prioritize([fakeFile('src/auth.ts', { additions: 5000 })], {
      maxFiles: 5,
      maxChangedLines: 10,
    });
    expect(selected).toHaveLength(1);
  });
});
