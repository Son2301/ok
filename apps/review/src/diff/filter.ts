import { matchAny } from './glob';
import type { DiffFile } from './types';

export type SkipReason =
  | 'deleted'
  | 'binary'
  | 'no-changes'
  | 'lockfile'
  | 'generated'
  | 'minified'
  | 'vendored'
  | 'snapshot'
  | 'large'
  | 'excluded'
  | 'not-included'
  | 'budget';

