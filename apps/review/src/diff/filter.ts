export interface FilterOptions {
  /** When non-empty, only matching files are reviewed. */
  include: readonly string[];
  /** Matching files are never reviewed. */
  exclude: readonly string[];
  /** Matching files are reviewed even if a built-in heuristic would skip them. */
  force: readonly string[];
  /** Files with more changed lines than this are skipped as `large`. */
  maxFileChangedLines: number;
}

export const DEFAULT_FILTER_OPTIONS: FilterOptions = {
  include: [],
  exclude: [],
  force: [],
  maxFileChangedLines: 1500,
};

const LOCKFILES = new Set([
  'package-lock.json',
  'npm-shrinkwrap.json',
  'pnpm-lock.yaml',
  'yarn.lock',
  'bun.lockb',
  'bun.lock',
  'deno.lock',
  'Cargo.lock',
  'Gemfile.lock',
  'poetry.lock',
  'Pipfile.lock',
  'pdm.lock',
  'uv.lock',
  'composer.lock',
  'go.sum',
  'mix.lock',
  'flake.lock',
  'Podfile.lock',
  'packages.lock.json',
  'gradle.lockfile',
  'pubspec.lock',
  'Package.resolved',
]);

const BINARY_EXT =
  /\.(png|jpe?g|gif|bmp|ico|webp|avif|tiff?|psd|pdf|zip|gz|tgz|bz2|xz|7z|rar|jar|war|class|exe|dll|so|dylib|a|o|obj|bin|wasm|woff2?|ttf|otf|eot|mp[34]|mov|avi|webm|ogg|wav|flac|sqlite|db|pyc|pkl|parquet|onnx|pt)$/i;

const VENDORED =
  /(^|\/)(vendor|node_modules|third[_-]party|bower_components|Pods|\.yarn|external|deps\/[^/]+\/src)\//;
const GENERATED_PATH =
  /(^|\/)(dist|build|out|\.next|coverage|__generated__|generated|gen)\/|\.generated\.|\.g\.dart$|\.pb\.go$|_pb2(_grpc)?\.py$|\.pb\.(cc|h)$|_generated\.go$|\.designer\.cs$|\.map$/;
const MINIFIED_PATH = /[.-]min\.(js|mjs|cjs|css)$/;
const SNAPSHOT = /(^|\/)__snapshots__\/|\.snap$|\.ambr$|\.golden$/;
const GENERATED_MARKER =
  /@generated|DO NOT EDIT|Code generated .* DO NOT EDIT|this file (is|was) (automatically |auto-)?generated|<auto-generated/i;

/** Why a file should be skipped, or null when it should be reviewed. */
export function classifyFile(
  file: DiffFile,
  opts: FilterOptions = DEFAULT_FILTER_OPTIONS,
): SkipReason | null {
  const path = file.path;
  if (file.status === 'deleted' || file.newPath === null) return 'deleted';
  if (file.binary || BINARY_EXT.test(path)) return 'binary';
  if (file.hunks.length === 0) return 'no-changes';
  if (opts.exclude.length && matchAny(path, opts.exclude)) return 'excluded';
  if (opts.include.length && !matchAny(path, opts.include)) return 'not-included';
  if (opts.force.length && matchAny(path, opts.force)) return null;

  const base = path.split('/').pop() ?? path;
  if (LOCKFILES.has(base)) return 'lockfile';
  if (VENDORED.test(path)) return 'vendored';
  if (SNAPSHOT.test(path)) return 'snapshot';
  if (MINIFIED_PATH.test(path) || looksMinified(file)) return 'minified';
  if (GENERATED_PATH.test(path) || hasGeneratedMarker(file)) return 'generated';
  if (file.additions + file.deletions > opts.maxFileChangedLines) return 'large';
  return null;
}

function looksMinified(file: DiffFile): boolean {
  let total = 0;
  let count = 0;
  let max = 0;
  for (const h of file.hunks) {
    for (const l of h.lines) {
      if (l.type !== 'add') continue;
      total += l.content.length;
      count++;
      if (l.content.length > max) max = l.content.length;
    }
  }
  return count > 0 && max > 1000 && total / count > 200;
}

/** Generated-file banners live in the first lines of a file. */
function hasGeneratedMarker(file: DiffFile): boolean {
  for (const h of file.hunks) {
    for (const l of h.lines) {
      if (l.newLine !== null && l.newLine <= 5 && GENERATED_MARKER.test(l.content)) return true;
    }
  }
  return false;
}

export interface SkippedFile {
  path: string;
  reason: SkipReason;
}

export function filterFiles(
  files: DiffFile[],
  opts: FilterOptions = DEFAULT_FILTER_OPTIONS,
): { kept: DiffFile[]; skipped: SkippedFile[] } {
  const kept: DiffFile[] = [];
  const skipped: SkippedFile[] = [];
  for (const f of files) {
    const reason = classifyFile(f, opts);
    if (reason) skipped.push({ path: f.path, reason });
    else kept.push(f);
  }
  return { kept, skipped };
}
